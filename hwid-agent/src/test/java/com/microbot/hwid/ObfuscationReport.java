package com.microbot.hwid;

import java.io.File;
import java.io.InputStream;
import java.io.Reader;
import java.math.BigInteger;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Properties;
import java.util.Set;
import java.util.TreeMap;
import java.util.regex.Pattern;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;
import org.objectweb.asm.ClassReader;
import org.objectweb.asm.Opcodes;
import org.objectweb.asm.Type;
import org.objectweb.asm.tree.AbstractInsnNode;
import org.objectweb.asm.tree.ClassNode;
import org.objectweb.asm.tree.FieldInsnNode;
import org.objectweb.asm.tree.LdcInsnNode;
import org.objectweb.asm.tree.MethodInsnNode;
import org.objectweb.asm.tree.MethodNode;

public final class ObfuscationReport
{
	private static final String START_MARKER = "<!-- obfuscation-values:start -->";
	private static final String END_MARKER = "<!-- obfuscation-values:end -->";
	private static final Pattern ACCESSOR = Pattern.compile("^(get|set|is)[A-Z].*");
	private static final BigInteger INT_MODULUS = BigInteger.ONE.shiftLeft(32);
	private static final BigInteger LONG_MODULUS = BigInteger.ONE.shiftLeft(64);
	private static final int MAX_ACCESSOR_INSTRUCTIONS = 30;
	private static final int MAX_FIELDS_PER_ACCESSOR = 4;

	private ObfuscationReport()
	{
	}

	public static void main(String[] args) throws Exception
	{
		if (args.length != 3)
		{
			throw new IllegalArgumentException("Usage: ObfuscationReport <hardening doc> <getters tsv> <menu-action properties>");
		}
		Path doc = Paths.get(args[0]);
		Path gettersFile = Paths.get(args[1]);
		Path menuActionFile = Paths.get(args[2]);

		File jar = InjectedClientJar.locate();
		if (jar == null)
		{
			throw new IllegalStateException("injected-client jar is not on the classpath");
		}
		String version = InjectedClientJar.version(jar);
		Map<String, byte[]> classes = readClasses(jar);
		Map<String, ClassNode> nodes = parse(classes);

		RandomDatTransformer.resetForTesting();
		runTransformer(new RandomDatTransformer(), classes);
		String fieldOwner = RandomDatTransformer.fieldOwner();
		String fieldName = RandomDatTransformer.fieldName();
		Map<String, Integer> hookedSites = countSites(RandomDatTransformer.patchedMethods());
		List<String> otherFieldAccessors = fieldOwner == null
			? Collections.emptyList()
			: methodsAccessing(nodes, fieldOwner, fieldName, hookedSites.keySet());

		RandomDatWriteTransformer.resetForTesting();
		runTransformer(new RandomDatWriteTransformer(), classes);
		List<String> fileGuards = new ArrayList<>(new LinkedHashSet<>(RandomDatWriteTransformer.patchedMethods()));

		List<String> deviceClasses = runTransformer(new PlatformInfoTransformer(), classes);
		List<String> deviceMethods = new ArrayList<>();
		for (String deviceClass : deviceClasses)
		{
			for (MethodNode method : nodes.get(deviceClass).methods)
			{
				if (Type.getReturnType(method.desc).getDescriptor().equals("Ljava/lang/String;")
					&& PlatformInfoTransformer.referencesMarkers(method))
				{
					deviceMethods.add(deviceClass + "." + method.name + method.desc);
				}
			}
		}

		List<String> deviceCallers = callersOf(nodes, deviceMethods);

		Properties menuAction = new Properties();
		if (Files.isRegularFile(menuActionFile))
		{
			try (Reader reader = Files.newBufferedReader(menuActionFile, StandardCharsets.ISO_8859_1))
			{
				menuAction.load(reader);
			}
		}

		List<String> getterRows = accessorRows(nodes);
		Files.createDirectories(gettersFile.toAbsolutePath().getParent());
		List<String> tsv = new ArrayList<>();
		tsv.add("# injected-client " + version + " - generated by scripts/update-obfuscation-values.sh, do not edit");
		tsv.add("class\tmethod\tfields\tmultiplier\tinverse");
		tsv.addAll(getterRows);
		Files.write(gettersFile, tsv, StandardCharsets.UTF_8);

		String block = buildBlock(version, fieldOwner, fieldName, hookedSites, otherFieldAccessors,
			fileGuards, deviceMethods, deviceCallers, menuAction, getterRows.size(), doc.toAbsolutePath().getParent().relativize(gettersFile.toAbsolutePath()));
		replaceBlock(doc, block);

		System.out.println("injected-client " + version);
		System.out.println("random.dat field: " + (fieldOwner == null ? "NOT FOUND" : fieldOwner + "." + fieldName));
		System.out.println("random.dat hooked sites: " + RandomDatTransformer.patchedSiteCount() + " in " + hookedSites.keySet());
		System.out.println("random.dat field accessed but not hooked: " + otherFieldAccessors);
		System.out.println("random.dat file guards: " + (fileGuards.isEmpty() ? "NOT FOUND" : fileGuards));
		System.out.println("device id methods: " + (deviceMethods.isEmpty() ? "NOT FOUND" : deviceMethods));
		System.out.println("device id callers: " + (deviceCallers.isEmpty() ? "none, the client never reads the device ID" : deviceCallers));
		System.out.println("accessor rows: " + getterRows.size() + " -> " + gettersFile);

		if (fieldOwner == null || hookedSites.isEmpty() || fileGuards.isEmpty() || deviceMethods.isEmpty())
		{
			System.err.println("A hook could not be located in injected-client " + version + "; the agent will not spoof it.");
			System.exit(1);
		}
	}

	private static Map<String, byte[]> readClasses(File jar) throws Exception
	{
		Map<String, byte[]> classes = new TreeMap<>();
		try (ZipFile zip = new ZipFile(jar))
		{
			for (ZipEntry entry : Collections.list(zip.entries()))
			{
				if (entry.isDirectory() || !entry.getName().endsWith(".class"))
				{
					continue;
				}
				try (InputStream in = zip.getInputStream(entry))
				{
					String name = entry.getName();
					classes.put(name.substring(0, name.length() - ".class".length()), in.readAllBytes());
				}
			}
		}
		return classes;
	}

	private static Map<String, ClassNode> parse(Map<String, byte[]> classes)
	{
		Map<String, ClassNode> nodes = new HashMap<>();
		for (Map.Entry<String, byte[]> entry : classes.entrySet())
		{
			ClassNode node = new ClassNode();
			new ClassReader(entry.getValue()).accept(node, ClassReader.SKIP_FRAMES | ClassReader.SKIP_DEBUG);
			nodes.put(entry.getKey(), node);
		}
		return nodes;
	}

	private static List<String> runTransformer(java.lang.instrument.ClassFileTransformer transformer, Map<String, byte[]> classes) throws Exception
	{
		List<String> order = new ArrayList<>();
		if (classes.containsKey("client"))
		{
			order.add("client");
		}
		for (String name : classes.keySet())
		{
			if (!name.equals("client"))
			{
				order.add(name);
			}
		}

		List<String> patched = new ArrayList<>();
		for (String name : order)
		{
			if (transformer.transform(null, name, null, null, classes.get(name)) != null)
			{
				patched.add(name);
			}
		}
		return patched;
	}

	private static Map<String, Integer> countSites(List<String> methods)
	{
		Map<String, Integer> counts = new LinkedHashMap<>();
		for (String method : methods)
		{
			counts.merge(method, 1, Integer::sum);
		}
		return counts;
	}

	private static List<String> methodsAccessing(Map<String, ClassNode> nodes, String owner, String name, Set<String> exclude)
	{
		Set<String> found = new LinkedHashSet<>();
		for (ClassNode node : new TreeMap<>(nodes).values())
		{
			for (MethodNode method : node.methods)
			{
				String key = node.name + "." + method.name + method.desc;
				if (exclude.contains(key))
				{
					continue;
				}
				for (AbstractInsnNode insn : method.instructions)
				{
					if (insn instanceof FieldInsnNode
						&& owner.equals(((FieldInsnNode) insn).owner)
						&& name.equals(((FieldInsnNode) insn).name))
					{
						found.add(key);
						break;
					}
				}
			}
		}
		return new ArrayList<>(found);
	}

	private static List<String> callersOf(Map<String, ClassNode> nodes, List<String> methods)
	{
		Set<String> callers = new LinkedHashSet<>();
		for (ClassNode node : new TreeMap<>(nodes).values())
		{
			for (MethodNode method : node.methods)
			{
				String key = node.name + "." + method.name + method.desc;
				for (AbstractInsnNode insn : method.instructions)
				{
					if (insn instanceof MethodInsnNode)
					{
						MethodInsnNode call = (MethodInsnNode) insn;
						String target = call.owner + "." + call.name + call.desc;
						if (methods.contains(target) && !methods.contains(key))
						{
							callers.add(key);
							break;
						}
					}
				}
			}
		}
		return new ArrayList<>(callers);
	}

	private static List<String> accessorRows(Map<String, ClassNode> nodes)
	{
		List<String> rows = new ArrayList<>();
		for (ClassNode node : new TreeMap<>(nodes).values())
		{
			if (node.name.contains("/"))
			{
				continue;
			}
			for (MethodNode method : node.methods)
			{
				if ((method.access & Opcodes.ACC_PUBLIC) == 0
					|| (method.access & (Opcodes.ACC_STATIC | Opcodes.ACC_ABSTRACT)) != 0
					|| !ACCESSOR.matcher(method.name).matches())
				{
					continue;
				}
				Access access = describe(method, nodes, 1);
				if (access == null || access.fields.isEmpty())
				{
					continue;
				}
				rows.add(node.name + "\t" + method.name + method.desc + "\t" + String.join(" > ", access.fields)
					+ "\t" + (access.multiplier == null ? "-" : access.multiplier) + "\t" + inverse(access.multiplier));
			}
		}
		return rows;
	}

	private static Access describe(MethodNode method, Map<String, ClassNode> nodes, int depth)
	{
		Set<String> fields = new LinkedHashSet<>();
		Number multiplier = null;
		MethodInsnNode delegate = null;
		int calls = 0;
		int size = 0;
		for (AbstractInsnNode insn : method.instructions)
		{
			if (insn.getOpcode() < 0)
			{
				continue;
			}
			if (++size > MAX_ACCESSOR_INSTRUCTIONS)
			{
				return null;
			}
			if (insn instanceof FieldInsnNode && !((FieldInsnNode) insn).owner.contains("/"))
			{
				FieldInsnNode field = (FieldInsnNode) insn;
				if (fields.size() < MAX_FIELDS_PER_ACCESSOR)
				{
					fields.add(field.owner + "." + field.name + ":" + field.desc);
				}
			}
			if (multiplier == null && insn instanceof LdcInsnNode && isMultiply(nextReal(insn)))
			{
				Object constant = ((LdcInsnNode) insn).cst;
				if (constant instanceof Integer || constant instanceof Long)
				{
					multiplier = (Number) constant;
				}
			}
			if (insn instanceof MethodInsnNode)
			{
				calls++;
				if (!((MethodInsnNode) insn).owner.contains("/"))
				{
					delegate = (MethodInsnNode) insn;
				}
			}
		}

		if (fields.isEmpty() && calls == 1 && delegate != null && depth > 0)
		{
			ClassNode target = nodes.get(delegate.owner);
			if (target != null)
			{
				for (MethodNode candidate : target.methods)
				{
					if (candidate.name.equals(delegate.name) && candidate.desc.equals(delegate.desc))
					{
						return describe(candidate, nodes, depth - 1);
					}
				}
			}
		}
		return new Access(fields, multiplier);
	}

	private static boolean isMultiply(AbstractInsnNode insn)
	{
		return insn != null && (insn.getOpcode() == Opcodes.IMUL || insn.getOpcode() == Opcodes.LMUL);
	}

	private static AbstractInsnNode nextReal(AbstractInsnNode insn)
	{
		AbstractInsnNode next = insn.getNext();
		while (next != null && next.getOpcode() < 0)
		{
			next = next.getNext();
		}
		return next;
	}

	static String inverse(Number multiplier)
	{
		if (multiplier == null)
		{
			return "-";
		}
		boolean isLong = multiplier instanceof Long;
		BigInteger value = BigInteger.valueOf(multiplier.longValue());
		if (!value.testBit(0))
		{
			return "-";
		}
		BigInteger inverse = value.modInverse(isLong ? LONG_MODULUS : INT_MODULUS);
		return isLong ? String.valueOf(inverse.longValue()) : String.valueOf(inverse.intValue());
	}

	private static String buildBlock(String version, String fieldOwner, String fieldName, Map<String, Integer> hookedSites,
		List<String> otherFieldAccessors, List<String> fileGuards, List<String> deviceMethods, List<String> deviceCallers, Properties menuAction, int accessorCount, Path gettersLink)
	{
		StringBuilder out = new StringBuilder();
		out.append(START_MARKER).append('\n');
		out.append("_Generated by `scripts/update-obfuscation-values.sh` against injected-client ").append(version)
			.append(". Do not edit by hand._\n\n");
		out.append("| Hook | Value |\n|---|---|\n");
		out.append("| random.dat field | ").append(fieldOwner == null ? "**not found**" : code(fieldOwner + "." + fieldName)).append(" |\n");
		int siteTotal = hookedSites.values().stream().mapToInt(Integer::intValue).sum();
		out.append("| random.dat hooked send sites (").append(siteTotal).append(") | ").append(codeList(hookedSites.keySet())).append(" |\n");
		out.append("| random.dat field accessed but not hooked | ").append(codeList(otherFieldAccessors)).append(" |\n");
		out.append("| random.dat file guarded while spoofing | ").append(fileGuards.isEmpty() ? "**not found**" : codeList(fileGuards)).append(" |\n");
		out.append("| Device ID methods | ").append(deviceMethods.isEmpty() ? "**not found**" : codeList(deviceMethods)).append(" |\n");
		out.append("| Device ID method callers | ").append(deviceCallers.isEmpty() ? "none: the client never reads the device ID, so the hook has nothing to replace" : codeList(deviceCallers)).append(" |\n");
		String menuOwner = menuAction.getProperty("menuAction.ownerClass");
		if (menuOwner != null)
		{
			out.append("| menuAction | ").append(code(menuOwner + "." + menuAction.getProperty("menuAction.methodName")
				+ menuAction.getProperty("menuAction.descriptor"))).append(", garbage ")
				.append(code(menuAction.getProperty("menuAction.garbageValue"))).append(" (")
				.append(menuAction.getProperty("menuAction.garbageKind")).append(") |\n");
		}
		out.append("| Injected accessors | ").append(accessorCount).append(" rows in [")
			.append(gettersLink.toString().replace('\\', '/')).append("](").append(gettersLink.toString().replace('\\', '/')).append(") |\n");
		out.append(END_MARKER);
		return out.toString();
	}

	private static String code(String value)
	{
		return "`" + value + "`";
	}

	private static String codeList(java.util.Collection<String> values)
	{
		if (values.isEmpty())
		{
			return "none";
		}
		List<String> coded = new ArrayList<>();
		for (String value : values)
		{
			coded.add(code(value));
		}
		return String.join(", ", coded);
	}

	private static void replaceBlock(Path doc, String block) throws Exception
	{
		String text = new String(Files.readAllBytes(doc), StandardCharsets.UTF_8);
		int start = text.indexOf(START_MARKER);
		int end = text.indexOf(END_MARKER);
		if (start < 0 || end < start)
		{
			throw new IllegalStateException(doc + " has no " + START_MARKER + " / " + END_MARKER + " block");
		}
		String updated = text.substring(0, start) + block + text.substring(end + END_MARKER.length());
		Files.write(doc, updated.getBytes(StandardCharsets.UTF_8));
	}

	private static final class Access
	{
		final Set<String> fields;
		final Number multiplier;

		Access(Set<String> fields, Number multiplier)
		{
			this.fields = fields;
			this.multiplier = multiplier;
		}
	}
}
